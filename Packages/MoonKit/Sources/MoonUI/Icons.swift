    /// nor an SF Symbol name.
    static func symbol(_ name: String) -> String? {
        if name.contains(".") { return name }
        return symbols[name] ?? (name.allSatisfy { $0.isLetter || $0.isNumber } ? name : nil)
    }

    /// The symbol for `name`, or a question mark where a label needs one.
    static func symbol(or name: String?, default fallback: String) -> String {
        name.flatMap(symbol) ?? fallback
